export let passedTests = 0;
export let failedTests = 0;
const failureDetails: Array<{ number: number; title: string; error: string }> = [];
const pendingPromises: Promise<any>[] = [];

export function runTest(testNumber: number, title: string, testFn: () => void | Promise<void>) {
  try {
    const result = testFn();
    if (result && typeof (result as any).then === 'function') {
      const p = (result as Promise<void>)
        .then(() => {
          console.log(`[PASS] Prueba ${testNumber.toString().padStart(3, '0')}: ${title}`);
          passedTests++;
        })
        .catch((err: any) => {
          console.error(`[FAIL] Prueba ${testNumber.toString().padStart(3, '0')}: ${title}`);
          console.error(`       Error: ${err?.message || err}`);
          failureDetails.push({ number: testNumber, title, error: err?.message || String(err) });
          failedTests++;
        });
      pendingPromises.push(p);
      return p;
    } else {
      console.log(`[PASS] Prueba ${testNumber.toString().padStart(3, '0')}: ${title}`);
      passedTests++;
    }
  } catch (err: any) {
    console.error(`[FAIL] Prueba ${testNumber.toString().padStart(3, '0')}: ${title}`);
    console.error(`       Error: ${err?.message || err}`);
    failureDetails.push({ number: testNumber, title, error: err?.message || String(err) });
    failedTests++;
  }
}

export async function waitForAllTests() {
  if (pendingPromises.length > 0) {
    await Promise.all(pendingPromises);
  }
}

export function printTestSummary() {
  console.log('\n================================================================');
  console.log(`RESUMEN FINAL DE AUDITORÍA: ${passedTests} APROBADAS / ${failedTests} FALLIDAS`);
  console.log('================================================================');
  if (failedTests > 0) {
    console.error('\nDETALLE DE PRUEBAS FALLIDAS:');
    failureDetails.forEach((f) => {
      console.error(`- Prueba ${f.number}: ${f.title}`);
      console.error(`  Error: ${f.error}`);
    });
    process.exit(1);
  } else {
    console.log(`¡TODAS LAS PRUEBAS (${passedTests} PRUEBAS) PASARON EXITOSAMENTE Y SIN ERRORES!`);
    process.exit(0);
  }
}

